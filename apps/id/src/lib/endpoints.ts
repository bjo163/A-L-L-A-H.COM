import { resolveEcosystemEndpoints } from '@moonwitness/ui';

export function getIdEcosystemEndpoints() {
  return resolveEcosystemEndpoints({
    NEXT_PUBLIC_ECOSYSTEM_HOSTNAME: process.env.NEXT_PUBLIC_ECOSYSTEM_HOSTNAME,
    NEXT_PUBLIC_ECOSYSTEM_ORIGIN: process.env.NEXT_PUBLIC_ECOSYSTEM_ORIGIN,
    NEXT_PUBLIC_ECOSYSTEM_DEV_HOSTNAME: process.env.NEXT_PUBLIC_ECOSYSTEM_DEV_HOSTNAME,
    NEXT_PUBLIC_ECOSYSTEM_PROTOCOL: process.env.NEXT_PUBLIC_ECOSYSTEM_PROTOCOL,
    NEXT_PUBLIC_DOCK_URL: process.env.NEXT_PUBLIC_DOCK_URL,
    NEXT_PUBLIC_HEADQUARTER_URL: process.env.NEXT_PUBLIC_HEADQUARTER_URL,
    NEXT_PUBLIC_ID_URL: process.env.NEXT_PUBLIC_ID_URL,
    NEXT_PUBLIC_JIZZ_URL: process.env.NEXT_PUBLIC_JIZZ_URL,
    NEXT_PUBLIC_GATE_URL: process.env.NEXT_PUBLIC_GATE_URL,
    NEXT_PUBLIC_MOONSKY_URL: process.env.NEXT_PUBLIC_MOONSKY_URL,
    NEXT_PUBLIC_HARBOR_URL: process.env.NEXT_PUBLIC_HARBOR_URL,
  });
}
